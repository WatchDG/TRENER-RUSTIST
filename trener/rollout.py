"""Rollout engine: generation of G trajectories per role and task from the snapshot `π̄`.

Sampling parameters are taken only from the configuration: `GenerationConfig`
is built explicitly, so the values from the model's `generation_config.json`
(`temperature=0.1`, `top_k=50`, `repetition_penalty=1.1`) are not mixed in.
"""

from __future__ import annotations

import logging
from collections.abc import Sequence
from dataclasses import dataclass, field
from typing import TYPE_CHECKING, Any

import torch
from transformers import GenerationConfig

from .architectures import architecture_of
from .media import Media, has_media

if TYPE_CHECKING:  # pragma: no cover - for type checking only
    from .config import RolloutConfig
    from .modeling import Policy
    from .prompts import PromptPair

logger = logging.getLogger(__name__)

#: Role identifiers.
TEACHER = "teacher"
STUDENT = "student"
ROLES = (TEACHER, STUDENT)

#: Seed offset for the second dialog turn (``tutor`` mode): the seeds of the two rounds differ.
ROUND_SEED_OFFSET = 1_000_000


@dataclass
class Trajectory:
    """One generated trajectory of a role.

    In ``tutor`` mode, ``completion_ids`` is the whole dialog after the prompt: the first turn
    of the model, the concatenation with the user's reply, and the second turn; ``train_mask``
    marks the tokens generated by the model (logp and the loss are computed on them), and
    ``n_completion_tokens`` is their count. ``text`` is the text of the model's last turn.
    Without a mask (``None``) all ``completion_ids`` tokens are trained on. ``media`` are the images and audio
    clips of the prompt: their tokens are in ``prompt_ids``, scoring passes them to the model.
    """

    task_id: str
    role: str
    prompt_ids: list[int]
    completion_ids: list[int]
    text: str
    n_completion_tokens: int
    prompt_len: int = 0
    meta: dict[str, Any] = field(default_factory=dict)
    train_mask: list[bool] | None = None
    media: Media | None = None

    def __post_init__(self) -> None:
        if not self.prompt_len:
            self.prompt_len = len(self.prompt_ids)


def _role_prompt(pair: PromptPair, role: str) -> tuple[list[int], str]:
    """Returns the ids and the text of the chosen role's prompt."""
    if role == TEACHER:
        return list(pair.teacher_ids), pair.teacher_text
    if role == STUDENT:
        return list(pair.student_ids), pair.student_text
    raise ValueError(f"unknown role {role!r}; allowed: {list(ROLES)}")


def _build_generation_config(
    policy: Policy,
    cfg: RolloutConfig,
    max_new_tokens: int,
    do_sample: bool,
) -> GenerationConfig:
    """Explicit `GenerationConfig`: the model's values must not be mixed in.

    `transformers` fills the passed config with values from the model's `generation_config.json`
    only for fields left as `None`, so all sampling fields are set explicitly. With greedy
    decoding (`do_sample=False`) the sampling fields get the `transformers` defaults; they do
    not affect the choice of token.
    """
    tokenizer = policy.tokenizer
    eos_token_id = tokenizer.eos_token_id
    if do_sample:
        temperature: float | None = float(cfg.temperature)
        top_p: float | None = float(cfg.top_p)
        top_k: int | None = int(cfg.top_k)
    else:
        temperature = 1.0
        top_p = 1.0
        top_k = 50
    config = GenerationConfig(
        do_sample=do_sample,
        temperature=temperature,
        top_p=top_p,
        top_k=top_k,
        repetition_penalty=float(cfg.repetition_penalty),
        max_new_tokens=int(max_new_tokens),
        min_new_tokens=0,
        pad_token_id=tokenizer.pad_token_id,
        eos_token_id=eos_token_id,
        bos_token_id=tokenizer.bos_token_id,
        use_cache=True,
    )
    # a model with its own `generate` (LFM3-Omni) refuses the fields it does not implement unless they are inert
    for name, inert in getattr(policy.model, "_generation_fields_unsupported", {}).items():
        if hasattr(config, name):
            setattr(config, name, inert)
    return config


def _trim_completion(ids: list[int], eos_token_id: Any, pad_token_id: Any) -> list[int]:
    """Trims the completion at EOS (inclusive) and removes trailing padding."""
    eos_ids: list[int] = []
    if isinstance(eos_token_id, (list, tuple)):
        eos_ids = [int(e) for e in eos_token_id]
    elif eos_token_id is not None:
        eos_ids = [int(eos_token_id)]

    for index, token in enumerate(ids):
        if token in eos_ids:
            return ids[: index + 1]

    end = len(ids)
    if pad_token_id is not None:
        while end > 0 and ids[end - 1] == int(pad_token_id):
            end -= 1
    return ids[:end]


def generate(
    policy: Policy,
    prompt_pairs: Sequence[PromptPair],
    cfg: RolloutConfig,
    role: str,
    *,
    group_size: int | None = None,
    max_new_tokens: int | None = None,
    do_sample: bool | None = None,
    seed: int | None = None,
    stats: dict[str, Any] | None = None,
) -> list[Trajectory]:
    """Generates `group_size` trajectories per prompt pair for role `role`.

    Trajectories are returned in the order "first all siblings of the first task, then
    the second one" — so the centering groups in `trener.weights` are aligned with the tasks.
    """
    return generate_roles(
        policy,
        prompt_pairs,
        cfg,
        (role,),
        group_size=group_size,
        max_new_tokens=max_new_tokens,
        do_sample=do_sample,
        seed=seed,
        stats=stats,
    )[role]


def generate_roles(
    policy: Policy,
    prompt_pairs: Sequence[PromptPair],
    cfg: RolloutConfig,
    roles: Sequence[str],
    *,
    group_size: int | None = None,
    max_new_tokens: int | None = None,
    do_sample: bool | None = None,
    seed: int | None = None,
    stats: dict[str, Any] | None = None,
) -> dict[str, list[Trajectory]]:
    """Generates trajectories for several roles from one snapshot `π̄`.

    Requests of all roles go in shared batches of `cfg.generation_batch_size` sequences:
    decoding in `transformers.generate` is limited by the latency of a step, not by the batch
    size, so the number of `generate` calls determines the rollout time. For each role,
    trajectories are returned in the order "task → siblings" (as in `generate`).

    The engine is selected by `cfg.engine`: `hf` — `transformers.generate` (reference),
    `static` — `trener.decode.StaticDecoder`; their trajectory format and order are the same.
    `stats` (optional) accumulates `calls` — the number of generation calls, `rows` — rows,
    `decode_steps` — decode steps (sum over the calls), `row_steps` — `rows × steps`
    (the denominator of the useful-token share).
    """
    for role in roles:
        if role not in ROLES:
            raise ValueError(f"unknown role {role!r}; allowed: {list(ROLES)}")
    result: dict[str, list[Trajectory]] = {role: [] for role in roles}
    if not prompt_pairs or not roles:
        return result

    group = int(group_size if group_size is not None else cfg.group_size)
    if group < 1:
        raise ValueError(f"group_size must be ≥ 1, got {group}")
    limit = int(max_new_tokens if max_new_tokens is not None else cfg.max_new_tokens)
    sampling = bool(cfg.temperature > 0) if do_sample is None else bool(do_sample)

    tokenizer = policy.tokenizer
    previous_padding_side = tokenizer.padding_side
    previous_training = policy.model.training
    previous_use_cache = getattr(policy.model.config, "use_cache", True)
    previous_generation_config = getattr(policy.model, "generation_config", None)

    if seed is not None:
        torch.manual_seed(int(seed))

    requests: list[tuple[str, int]] = [
        (role, pair_index) for role in roles for pair_index in range(len(prompt_pairs)) for _ in range(group)
    ]
    generation_config = _build_generation_config(policy, cfg, limit, sampling)
    engine = str(getattr(cfg, "engine", "hf"))
    decoder = None
    if engine == "static":
        from .decode import get_decoder

        decoder = get_decoder(policy, cfg)

    try:
        tokenizer.padding_side = "left"
        policy.set_use_cache(True)
        policy.eval()
        # `transformers` fills the passed config with values from `model.generation_config`
        # (the model's `generation_config.json`); swapping it for the generation time rules out
        # mixing structurally, rather than by enumerating fields.
        if previous_generation_config is not None:
            policy.model.generation_config = generation_config

        micro = max(1, int(getattr(cfg, "generation_batch_size", 0) or cfg.micro_batch_size))

        def run_round(prompts: list[list[int]], seed_offset: int, media: list[Media | None]) -> list[list[int]]:
            """One generation for a list of prompts (with their media): continuations trimmed at EOS, in order."""
            completions: list[list[int]] = []
            for start in range(0, len(prompts), micro):
                chunk = prompts[start : start + micro]
                chunk_media = media[start : start + micro]
                if decoder is not None:
                    decoded = decoder.generate(
                        chunk,
                        max_new_tokens=limit,
                        do_sample=sampling,
                        seed=((int(seed) + seed_offset) * 1_000_003 + start) if seed is not None else None,
                        media=chunk_media,
                    )
                    generated = decoded.completions
                    steps = decoded.decode_steps
                else:
                    batch = tokenizer.pad(
                        {"input_ids": chunk},
                        return_tensors="pt",
                        padding=True,
                    )
                    input_ids = batch["input_ids"].to(policy.device)
                    attention_mask = batch["attention_mask"].to(policy.device)

                    with torch.no_grad():
                        outputs = policy.model.generate(
                            input_ids=input_ids,
                            attention_mask=attention_mask,
                            generation_config=generation_config,
                            **_media_inputs(policy, chunk_media),
                            **architecture_of(policy.model).hf_generate_kwargs,
                        )

                    prompt_width = input_ids.shape[1]
                    generated = outputs[:, prompt_width:].tolist()
                    steps = len(generated[0]) if generated else 0
                if stats is not None:
                    stats["calls"] = stats.get("calls", 0) + 1
                    stats["rows"] = stats.get("rows", 0) + len(chunk)
                    stats["decode_steps"] = stats.get("decode_steps", 0) + steps
                    stats["row_steps"] = stats.get("row_steps", 0) + len(chunk) * steps
                completions.extend(_trim_completion(ids, policy.stop_ids, tokenizer.pad_token_id) for ids in generated)
            return completions

        role_prompts = [_role_prompt(prompt_pairs[pair_index], role)[0] for role, pair_index in requests]
        role_media = [getattr(prompt_pairs[pair_index], "media", None) for _, pair_index in requests]
        first_turns = run_round(role_prompts, 0, role_media)

        # Tutor mode: after the first turn the user's reply is inserted, and the second turn follows.
        dialog = [
            index
            for index, (_, pair_index) in enumerate(requests)
            if getattr(prompt_pairs[pair_index], "glue_ids", None) is not None
        ]
        second_turns: dict[int, list[int]] = {}
        sampled_first: dict[int, list[int]] = {}
        if dialog:
            eos = tokenizer.eos_token_id
            contexts: list[list[int]] = []
            for index in dialog:
                first = first_turns[index]
                sampled_first[index] = first
                closed = first if first and first[-1] == eos else [*first, int(eos)]
                first_turns[index] = closed
                glue = prompt_pairs[requests[index][1]].glue_ids
                contexts.append([*role_prompts[index], *closed, *glue])
            dialog_media = [role_media[index] for index in dialog]
            for index, second in zip(dialog, run_round(contexts, ROUND_SEED_OFFSET, dialog_media), strict=True):
                second_turns[index] = second

        for index, ((role, pair_index), ids_prompt) in enumerate(zip(requests, role_prompts, strict=True)):
            pair = prompt_pairs[pair_index]
            task_id = _task_id(pair, pair_index)
            first = first_turns[index]
            if index not in second_turns:
                result[role].append(_single_turn(tokenizer, task_id, role, ids_prompt, first, role_media[index]))
                continue
            glue = pair.glue_ids
            second = second_turns[index]
            n_sampled_first = len(sampled_first[index])
            train_mask = (
                [True] * n_sampled_first + [False] * (len(first) - n_sampled_first + len(glue)) + [True] * len(second)
            )
            text = tokenizer.decode(second, skip_special_tokens=True)
            result[role].append(
                Trajectory(
                    task_id=task_id,
                    role=role,
                    prompt_ids=list(ids_prompt),
                    completion_ids=[*first, *glue, *second],
                    text=text,
                    n_completion_tokens=sum(train_mask),
                    prompt_len=len(ids_prompt),
                    train_mask=train_mask,
                    meta={
                        "turns": {
                            "question": tokenizer.decode(first, skip_special_tokens=True),
                            "user": pair.user_reply,
                            "evaluation": text,
                        }
                    },
                )
            )
    finally:
        tokenizer.padding_side = previous_padding_side
        if previous_generation_config is not None:
            policy.model.generation_config = previous_generation_config
        policy.set_use_cache(previous_use_cache)
        if previous_training:
            policy.train()
        else:
            policy.eval()

    for role, trajectories in result.items():
        logger.debug(
            "generated %d trajectories for role %s (%d completion tokens)",
            len(trajectories),
            role,
            sum(t.n_completion_tokens for t in trajectories),
        )
    return result


def _task_id(pair: Any, pair_index: int) -> str:
    """Task identifier of a prompt pair (by default, its index in the batch)."""
    return getattr(pair, "task_id", None) or str(pair_index)


def _single_turn(
    tokenizer: Any,
    task_id: str,
    role: str,
    prompt_ids: Sequence[int],
    completion: list[int],
    media: Media | None = None,
) -> Trajectory:
    """Trajectory of a single model turn (no dialog): all completion tokens are trained on."""
    return Trajectory(
        task_id=task_id,
        role=role,
        prompt_ids=list(prompt_ids),
        completion_ids=completion,
        text=tokenizer.decode(completion, skip_special_tokens=True),
        n_completion_tokens=len(completion),
        prompt_len=len(prompt_ids),
        media=media,
    )


def _media_inputs(policy: Policy, media: Sequence[Media | None]) -> dict[str, torch.Tensor]:
    """Media arguments of the model's own `generate` for the rows of a batch (row by row)."""
    if not has_media(media):
        return {}
    encoder = policy.media
    if encoder is None:
        raise ValueError("the prompts carry media, but the model takes none (text-only model)")
    inputs: dict[str, torch.Tensor] = {}
    images = [ref for entry in media if entry is not None for ref in entry.images]
    if images and encoder.images is not None:
        pixel_values, grid = encoder.images.pixels(images)
        inputs |= {"pixel_values": pixel_values.to(policy.device), "image_grid_thw": grid.to(policy.device)}
    clips = [ref for entry in media if entry is not None for ref in entry.audio]
    if clips and encoder.audio is not None:
        features, mask = encoder.audio.features(clips)
        inputs |= {"input_features": features.to(policy.device), "feature_attention_mask": mask.to(policy.device)}
    return inputs


class RolloutStream:
    """Rollout whose trajectories arrive as the decode rows finish (`start_roles`).

    `poll` returns `[(role, index within role, trajectory)]`: the index is the position the
    trajectory would take in the result of `generate_roles` (order "task → siblings").
    """

    def __init__(
        self,
        policy: Policy,
        prompt_pairs: Sequence[PromptPair],
        requests: list[tuple[str, int]],
        role_prompts: list[list[int]],
        session: Any,
    ) -> None:
        self.policy = policy
        self.prompt_pairs = prompt_pairs
        self.requests = requests
        self.role_prompts = role_prompts
        self.session = session
        self._position: list[int] = []
        seen: dict[str, int] = {}
        for role, _ in requests:
            self._position.append(seen.get(role, 0))
            seen[role] = seen.get(role, 0) + 1

    @property
    def done(self) -> bool:
        """All trajectories have been received."""
        return bool(self.session.done)

    @property
    def threaded(self) -> bool:
        """Decoding runs in a separate thread (the main thread is free)."""
        return bool(self.session.threaded)

    def poll(self, block: bool = False) -> list[tuple[str, int, Trajectory]]:
        """Trajectories of the rows finished since the last call (see `DecodeSession.poll`)."""
        tokenizer = self.policy.tokenizer
        result: list[tuple[str, int, Trajectory]] = []
        for row, ids in self.session.poll(block=block):
            role, pair_index = self.requests[row]
            completion = _trim_completion(ids, self.policy.stop_ids, tokenizer.pad_token_id)
            pair = self.prompt_pairs[pair_index]
            task_id = _task_id(pair, pair_index)
            media = getattr(pair, "media", None)
            trajectory = _single_turn(tokenizer, task_id, role, self.role_prompts[row], completion, media)
            result.append((role, self._position[row], trajectory))
        return result

    def finish(self, stats: dict[str, Any] | None = None) -> None:
        """Finishes decoding; `stats` receives the same counters as in `generate_roles`."""
        steps = self.session.finish()
        if stats is not None:
            rows = len(self.requests)
            stats["calls"] = stats.get("calls", 0) + 1
            stats["rows"] = stats.get("rows", 0) + rows
            stats["decode_steps"] = stats.get("decode_steps", 0) + steps
            stats["row_steps"] = stats.get("row_steps", 0) + rows * steps

    def cancel(self) -> None:
        """Stops decoding (an error in the calling code)."""
        self.session.cancel()


def start_roles(
    policy: Policy,
    prompt_pairs: Sequence[PromptPair],
    cfg: RolloutConfig,
    roles: Sequence[str],
    *,
    seed: int | None = None,
) -> RolloutStream | None:
    """Starts a rollout of roles whose trajectories arrive as they become ready.

    The trajectories are the same as those of `generate_roles` with the same arguments (same
    snapshot, seed and row order). `None` means the streaming rollout is not applicable, and
    the caller uses `generate_roles`: the engine is not `static`, there is a dialog (tutor mode),
    or there are more rows than `generation_batch_size` (several generation calls).
    """
    if str(getattr(cfg, "engine", "hf")) != "static" or not prompt_pairs or not roles:
        return None
    for role in roles:
        if role not in ROLES:
            raise ValueError(f"unknown role {role!r}; allowed: {list(ROLES)}")
    if any(getattr(pair, "glue_ids", None) is not None for pair in prompt_pairs):
        return None
    group = int(cfg.group_size)
    requests = [(role, index) for role in roles for index in range(len(prompt_pairs)) for _ in range(group)]
    micro = max(1, int(getattr(cfg, "generation_batch_size", 0) or cfg.micro_batch_size))
    if len(requests) > micro:
        return None

    from .decode import get_decoder

    if seed is not None:
        torch.manual_seed(int(seed))
    role_prompts = [_role_prompt(prompt_pairs[pair_index], role)[0] for role, pair_index in requests]
    session = get_decoder(policy, cfg).start(
        role_prompts,
        max_new_tokens=int(cfg.max_new_tokens),
        do_sample=bool(cfg.temperature > 0),
        # the same seed as the first (and only) generation call in `generate_roles`
        seed=int(seed) * 1_000_003 if seed is not None else None,
        media=[getattr(prompt_pairs[pair_index], "media", None) for _, pair_index in requests],
    )
    return RolloutStream(policy, prompt_pairs, requests, role_prompts, session)


def group_sizes(trajectories: Sequence[Trajectory]) -> dict[str, int]:
    """How many trajectories each task has (for centering)."""
    counts: dict[str, int] = {}
    for trajectory in trajectories:
        counts[trajectory.task_id] = counts.get(trajectory.task_id, 0) + 1
    return counts


